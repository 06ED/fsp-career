package ru.fsp.career.assessment.domain

import kotlin.math.abs
import kotlin.math.exp
import kotlin.math.ln
import kotlin.math.roundToInt
import kotlin.math.sqrt

/**
 * Item response theory core shared by the API and the validation simulation.
 *
 * Every item family carries 2PL parameters: `a` (discrimination) and `b` (difficulty) on the
 * latent ability scale θ (population ~ N(0, 1)). Multiple-choice families additionally get a
 * fixed lower asymptote `c = 1 / options` (guessing), i.e. a 3PL with c fixed by the response
 * format; numeric-input families have c = 0. All instances generated by one family share these
 * parameters — that is what makes different concrete tasks comparable.
 */
data class ItemParams(val a: Double, val b: Double, val c: Double = 0.0)

object Irt {
    /** P(correct | θ) = c + (1 − c) / (1 + e^(−a(θ − b))). */
    fun probability(item: ItemParams, theta: Double): Double {
        val logistic = 1.0 / (1.0 + exp(-item.a * (theta - item.b)))
        return item.c + (1.0 - item.c) * logistic
    }

    /**
     * Fisher information I(θ) = a² · (Q / P) · ((P − c) / (1 − c))²  (Birnbaum's 3PL formula; equals a²PQ
     * when c = 0). The CAT picks the family with the largest information at the current estimate.
     */
    fun information(item: ItemParams, theta: Double): Double {
        val p = probability(item, theta)
        val q = 1.0 - p
        if (p <= 0.0 || q <= 0.0) return 0.0
        val x = (p - item.c) / (1.0 - item.c)
        return item.a * item.a * (q / p) * x * x
    }

    /** Standard normal CDF Φ (Abramowitz–Stegun 7.1.26 erf approximation, |error| < 1.5e-7). */
    fun normalCdf(x: Double): Double {
        val z = abs(x) / sqrt(2.0)
        val t = 1.0 / (1.0 + 0.3275911 * z)
        val poly = t * (0.254829592 + t * (-0.284496736 + t * (1.421413741 + t * (-1.453152027 + t * 1.061405429))))
        val erf = 1.0 - poly * exp(-z * z)
        return if (x >= 0) 0.5 * (1.0 + erf) else 0.5 * (1.0 - erf)
    }

    /** Quadrature grid for EAP: θ ∈ [−4; 4] with step 0.05. */
    val grid: DoubleArray = DoubleArray(161) { -4.0 + it * 0.05 }
}

data class Estimate(val theta: Double, val se: Double)

/**
 * Accumulates the log-likelihood of a response pattern on the quadrature grid, so each new answer
 * costs O(grid) and the posterior can be read under any normal prior.
 *
 * EAP (expected a posteriori) = posterior mean, SE = posterior SD. Unlike maximum likelihood it is
 * finite for all-correct / all-wrong patterns, which matters for a 12-item test.
 */
class LikelihoodGrid {
    private val logLik = DoubleArray(Irt.grid.size)
    var count: Int = 0
        private set

    fun add(item: ItemParams, correct: Boolean) {
        for (i in Irt.grid.indices) {
            val p = Irt.probability(item, Irt.grid[i]).coerceIn(1e-9, 1.0 - 1e-9)
            logLik[i] += if (correct) ln(p) else ln(1.0 - p)
        }
        count++
    }

    fun posterior(priorMean: Double = 0.0, priorSd: Double = 1.0): Estimate {
        val logPost = DoubleArray(Irt.grid.size) { i ->
            val z = (Irt.grid[i] - priorMean) / priorSd
            logLik[i] - 0.5 * z * z
        }
        val max = logPost.max()
        var total = 0.0
        var mean = 0.0
        val weights = DoubleArray(logPost.size) { exp(logPost[it] - max) }
        for (i in weights.indices) { total += weights[i]; mean += weights[i] * Irt.grid[i] }
        mean /= total
        var variance = 0.0
        for (i in weights.indices) { val d = Irt.grid[i] - mean; variance += weights[i] * d * d }
        return Estimate(mean, sqrt(variance / total))
    }

    companion object {
        fun of(responses: List<Pair<ItemParams, Boolean>>): LikelihoodGrid =
            LikelihoodGrid().also { grid -> responses.forEach { (item, correct) -> grid.add(item, correct) } }
    }
}

/**
 * Grade scale. Cut-points are on θ (population N(0, 1)):
 *  - middle/senior boundary at θ = +0.8  (≈ top 21 % of the reference population),
 *  - junior/middle boundary at θ = −0.5  (≈ 31 % below),
 *  - "entry" cut for a junior target at θ = −1.5 (≈ 7 % below: the entry level is not demonstrated;
 *    the category stays Junior by the floor rule, but the attempt is recorded as not passed).
 * `anchor` is where the adaptive test starts for a declared target grade (routing only — never used
 * for the scoring prior, so the declaration cannot inflate a result).
 */
enum class Grade(val id: String, val label: String, val cut: Double, val anchor: Double) {
    JUNIOR("junior", "Junior", -1.5, -1.0),
    MIDDLE("middle", "Middle", -0.5, 0.15),
    SENIOR("senior", "Senior", 0.8, 1.4);

    val rank: Int get() = ordinal + 1
    fun next(): Grade? = entries.getOrNull(ordinal + 1)
    fun previous(): Grade? = entries.getOrNull(ordinal - 1)

    companion object {
        fun of(id: String?): Grade? = entries.firstOrNull { it.id == id }

        /** Reference ("true") grade used by the validation: the band θ falls into. */
        fun reference(theta: Double): Grade = when {
            theta >= SENIOR.cut -> SENIOR
            theta >= MIDDLE.cut -> MIDDLE
            else -> JUNIOR
        }

        fun max(a: Grade?, b: Grade?): Grade? = listOfNotNull(a, b).maxByOrNull { it.ordinal }
    }
}

data class Decision(
    val estimate: Estimate,
    val score: Int,
    val passed: Boolean,
    val confident: Boolean,
)

object Grading {
    /**
     * Decision margin k: the target grade is confirmed when θ̂ − k·SE ≥ cut(target). Under the normal
     * posterior approximation this is "P(θ ≥ cut | answers) ≥ Φ(k)". The EAP estimate is already shrunk
     * towards the population mean, and the validation sweep (docs/validation/assessment-results.md, §8)
     * shows that any extra margin costs more under-grading than it saves in over-grading — even when
     * over-grading is counted twice as expensive. Hence k = 0: confirm when the posterior is ≥ 50 % on the
     * target side of the cut. The parameter stays explicit so a pilot can retune it.
     */
    const val K: Double = 0.0

    /**
     * Margin for "confident" (unlocks an immediate test one grade higher). It only grants another attempt —
     * the higher grade must still be passed with margin K — so it can be lenient; see the validation sweep.
     */
    const val K_UPGRADE: Double = 0.0

    /** Normalized 0..100 score = 100 · Φ(θ̂): the percentile of θ̂ in the reference population. */
    fun score(theta: Double): Int = (100.0 * Irt.normalCdf(theta)).roundToInt().coerceIn(0, 100)

    /**
     * "Confident" = θ̂ − K_UPGRADE·SE also clears the next grade's cut; it unlocks an immediate attempt
     * for the next grade (the spec's "справившийся уверенно – повысить грейд").
     */
    fun decide(target: Grade, estimate: Estimate, k: Double = K, kUpgrade: Double = K_UPGRADE): Decision {
        val passed = estimate.theta - k * estimate.se >= target.cut
        val next = target.next()
        val confident = passed && next != null && estimate.theta - kUpgrade * estimate.se >= next.cut
        return Decision(estimate, score(estimate.theta), passed, confident)
    }

    /** A failure preserves a previous confirmation, but cannot create one. */
    fun confirmedAfter(previous: Grade?, target: Grade, passed: Boolean): Grade? =
        Grade.max(previous, if (passed) target else null)
}
